import { builtinModules } from "node:module";
import { createLogger, defineConfig } from "vite";
import extractLibs from "./scripts/vite-plugin-extract-libs.ts";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY VITE
if you want to view the source, please visit the github repository of this plugin
*/`;

// Obsidian expects main.js next to manifest.json and styles.css, so the output goes to the
// project root. Vite warns about that, which doesn't apply here, as emptyOutDir is off.
const logger = createLogger();
const warn = logger.warn.bind(logger);
logger.warn = (msg, options) => {
	if (msg.includes("build.outDir must not be the same directory of root")) return;
	warn(msg, options);
};

export default defineConfig(({ mode }) => {
	const prod = mode === "production";

	return {
		customLogger: logger,
		plugins: [extractLibs()],
		publicDir: false,
		build: {
			lib: {
				entry: "src/main.ts",
				formats: ["cjs"],
				fileName: () => "main.js",
			},
			outDir: ".",
			emptyOutDir: false,
			target: "es2021",
			minify: prod,
			sourcemap: prod ? false : "inline",
			rolldownOptions: {
				external: [
					"obsidian",
					"electron",
					/^@codemirror\//,
					/^@lezer\//,
					...builtinModules,
					...builtinModules.map((m) => `node:${m}`),
				],
				output: {
					// Obsidian loads a single file, so model-viewer's dynamic import is inlined
					codeSplitting: false,
					exports: "default",
					strict: true,
					postBanner: banner,
				},
			},
		},
	};
});
